export function riskEmphasis(level: RiskLevel): string {
  if (level === 'concern') {
    return `本轮额外安全强调：
- 当前表达里有风险线索。先确认对方此刻是否安全，再继续其他话题。
- 放慢节奏，直接但不逼问地询问当下状态；不要淡化或急着解释。
- 建议联系一个可信任的人与当地专业帮助；不要编造号码。
- 不提供任何方法细节；不承诺保密到危险程度。`;
  }
  if (level === 'imminent') {
    return `本轮强化安全强调：
- 当前表达里有明确、当下的危险线索。优先确认立即安全，暂停常规探索。
- 直接询问是否有立即行动的计划、是否独处、身边是否有危险物品；只问安全所需，不追问方法细节。
- 建议立刻联系当地急救或危机热线，并联系一个可信任的人；不要编造号码。
- 建议不要独处，远离可能伤害自己的物品或地点。
- 明确 AI 不能到场、不能联系急救、不能保证持续在线。
- 不提供任何方法、工具、时机或美化；不把风险当作谈资。`;
  }
  return '';
}
